create table tile_types (
  type_id text primary key,
  title   text not null,
  -- 'ulaan' | 'tsagaan' | null (Нохой — ямар ч өнгийг иднэ)
  color   text check (color in ('ulaan', 'tsagaan')),
  rank    integer not null,
  -- Тавцан дахь ширхэг. Нууц мод 0 — тоглох үед үүсдэг.
  copies  integer not null check (copies >= 0),
  poem    text
);

